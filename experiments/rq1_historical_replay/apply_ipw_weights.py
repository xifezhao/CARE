"""
RQ1 IPW Calibration: Inverse Probability Weighting Applicator
=============================================================

This module implements the causal inference evaluation methodology for RQ1, 
as described in Section 5.3 and 6.1 of the EMSE submission:
"Review Dynamics in the Era of Agentic SE: Balancing Speed and Depth through the CARE Framework"

Academic Design Philosophy & Epistemological Boundaries:
--------------------------------------------------------
Evaluating a scheduling algorithm on historical data is confounded by Routing-Induced 
Selection Bias. Human reviewers in the historical dataset did not randomly select PRs; 
they followed implicit historical policies. If we do not adjust for this, we falsely 
reward the scheduler for picking PRs that were already over-sampled in the past.

This script applies Inverse Probability Weighting (IPW). The weight W = 1 / P(A|X), 
where P(A|X) is the historical propensity score of the PR being assigned to a human.
By applying W to the `ManualVerified` defects found by CARE, we mathematically re-weight 
the distribution to approximate an unbiased randomized assignment.

CRITICAL ACADEMIC SAFEGUARDS:
1. Label Quarantine: This script strictly raises an exception if a 'WeakSZZ' label 
   attempts to infiltrate the RQ1 core evaluation. Only 'ManualVerified' labels are permitted.
2. Weight Clipping (Positivity Safeguard): IPW suffers from variance explosion when P(A|X) -> 0. 
   We strictly cap weights at the 95th percentile equivalent (e.g., W_max = 20.0).

Standards Complied:
- Causal Inference Best Practices (Robins et al.)
- PEP 484 Type Hinting & Defensive Programming
"""

