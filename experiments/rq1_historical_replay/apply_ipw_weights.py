# ============================================================================
# Data Loaders & Validators
# ============================================================================

def load_ground_truth_labels(filepath: str) -> Dict[str, TieredLabelSpace]:
    """
    Loads the 2D Tiered Label Space, ensuring epistemological separation of label strengths.
    """
    logger.info(f"Loading Ground Truth labels from {filepath}...")
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Ground truth file missing: {filepath}")
        
    labels = {}
    with open(filepath, 'r', encoding='utf-8') as f:
        raw_data = json.load(f)
        for record in raw_data:
            strength_enum = LabelStrength(record["strength"])
            labels[record["pr_id"]] = TieredLabelSpace(
                pr_id=record["pr_id"],
                observation_days=record["observation_days"],
                defect_observed=record["defect_observed"],
                strength=strength_enum
            )
    return labels

def load_propensity_scores(filepath: str) -> Dict[str, float]:
    """
    Loads historical propensity scores P(A|X) computed via logistic regression 
    or covariate matching prior to the evaluation.
    """
    logger.info(f"Loading Propensity Scores P(A|X) from {filepath}...")
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Propensity scores file missing: {filepath}")
        
    with open(filepath, 'r', encoding='utf-8') as f:
        scores = json.load(f)
        
    # Validation
    for pr_id, p_score in scores.items():
        if not (0.0 <= p_score <= 1.0):
            raise ValueError(f"Propensity score for PR {pr_id} out of bounds [0,1]: {p_score}")
    return scores

def load_simulation_trajectory(filepath: str) -> List[Dict[str, Any]]:
    """Loads the daily scheduling trajectories generated by simulate_queues.py."""
    logger.info(f"Loading simulation trajectory from {filepath}...")
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"Trajectory file missing: {filepath}")
        
    with open(filepath, 'r', encoding='utf-8') as f:
        return json.load(f)

# ============================================================================
# IPW Application Engine
# ============================================================================

def evaluate_trajectory_with_ipw(
    trajectory: List[Dict[str, Any]], 
    labels: Dict[str, TieredLabelSpace], 
    p_scores: Dict[str, float],
    max_weight_cap: float = 20.0
) -> float:
    """
    Translates a simulated trajectory into IPW-weighted Cumulative Yield.
    
    Args:
        trajectory: The output from simulate_queues.py (List of daily scheduled PRs).
        labels: The ground truth TieredLabelSpace dictionary.
        p_scores: Propensity scores dictionary.
        max_weight_cap: Weight clipping threshold to preserve Positivity Assumption.
        
    Returns:
        float: The final IPW-adjusted Cumulative Yield for RQ1.
    """
    calibrator = IPWCalibrator(max_weight_cap=max_weight_cap)
    calibration_records: List[CalibrationRecord] = []
    
    total_scheduled_count = 0
    missing_p_score_count = 0
    
    for daily_record in trajectory:
        scheduled_pr_ids = daily_record.get("scheduled", [])
        total_scheduled_count += len(scheduled_pr_ids)
        
        for pr_id in scheduled_pr_ids:
            # 1. Fetch label (If missing, assume right-censored NA)
            label = labels.get(
                pr_id, 
                TieredLabelSpace(pr_id, observation_days=180.0, defect_observed=False, strength=LabelStrength.NA)
            )
            
            # 2. Fetch propensity score
            p_score = p_scores.get(pr_id)
            if p_score is None:
                missing_p_score_count += 1
                continue
                
            # 3. Construct the observation record (assigned_to_human=True because it was scheduled)
            record = CalibrationRecord(
                pr_id=pr_id,
                assigned_to_human=True,
                propensity_score=p_score,
                label=label
            )
            calibration_records.append(record)

    if missing_p_score_count > 0:
        logger.warning(
            f"Missing Propensity Scores for {missing_p_score_count} scheduled PRs. "
            f"These records will be excluded, which may slightly deflate the cumulative yield."
        )

    # 4. Execute the mathematically rigorous IPW calculation
    # NOTE: The compute_weighted_yield method internally enforces the Label Quarantine (rejects WeakSZZ)
    # and handles the Weight Clipping logic.
    try:
        ipw_yield = calibrator.compute_weighted_yield(calibration_records)
    except ValueError as e:
        logger.error("CRITICAL ACADEMIC VIOLATION DETECTED DURING EVALUATION.")
        raise e

    logger.info(
        f"Trajectory Evaluation Complete.\n"
        f"  Total Scheduled Tasks: {total_scheduled_count}\n"
        f"  Valid Records for IPW: {len(calibration_records)}\n"
        f"  IPW-Weighted Yield:    {ipw_yield:.2f}"
    )
    
    return ipw_yield


