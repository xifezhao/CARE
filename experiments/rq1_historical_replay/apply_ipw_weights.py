    # 1. Load rigorous academic inputs
    labels_path = os.path.join(DATA_DIR, "manual_audit", "IRR_ManualVerified_Labels.json")
    pscores_path = os.path.join(DATA_DIR, "processed", "propensity_scores_2025.json")
    
    try:
        gt_labels = load_ground_truth_labels(labels_path)
        propensity_scores = load_propensity_scores(pscores_path)
    except FileNotFoundError as e:
        logger.error(f"Missing required dataset for RQ1 IPW evaluation: {e}")
        exit(1)

    # 2. Evaluate FIFO Baseline Trajectory
    logger.info("--- Evaluating FIFO Baseline ---")
    fifo_traj_path = os.path.join(RESULTS_DIR, "fifo_trajectory.json")
    fifo_trajectory = load_simulation_trajectory(fifo_traj_path)
    fifo_yield = evaluate_trajectory_with_ipw(
        fifo_trajectory, gt_labels, propensity_scores, max_weight_cap=20.0
    )
    
    # 3. Evaluate CARE Heuristic Trajectory
    logger.info("--- Evaluating CARE Heuristic Scheduler ---")
    care_traj_path = os.path.join(RESULTS_DIR, "care_trajectory.json")
    care_trajectory = load_simulation_trajectory(care_traj_path)
    care_yield = evaluate_trajectory_with_ipw(
        care_trajectory, gt_labels, propensity_scores, max_weight_cap=20.0
    )
    
    # 4. Save comparative IPW results
    comparison_result = {
        "budget_level": "20_percent_strict", # Reflecting Fig 4 Critical Point
        "fifo_ipw_yield": fifo_yield,
        "care_ipw_yield": care_yield,
        "absolute_lift": care_yield - fifo_yield,
        "relative_improvement_pct": ((care_yield - fifo_yield) / max(fifo_yield, 1.0)) * 100
    }
    
    out_path = os.path.join(RESULTS_DIR, "ipw_evaluation_summary.json")
    with open(out_path, 'w') as f:
        json.dump(comparison_result, f, indent=4)
        
    logger.info(f"RQ1 IPW Evaluation Summary successfully written to {out_path}")
    logger.info(f"CARE Yield: {care_yield:.2f} vs FIFO Yield: {fifo_yield:.2f}")
