"""
Phase 5: Bias-Aware Calibration (IPW & Stratified Auditing)
===========================================================

This module implements the formalization described in Section 4.5 of the EMSE submission:
"Review Dynamics in the Era of Agentic SE: Balancing Speed and Depth through the CARE Framework"

Academic Design Philosophy:
---------------------------
Historical code review data generated by a risk-aware scheduler suffers from severe 
Selection Bias: human reviewers only find defects in PRs the scheduler assigned to them.
Training a heuristic proxy (ΔY_hat) directly on this observational distribution mathematically 
reinforces the routing bias (Confirmation Bias Loop).

Key Formalizations (Equation 7):
1. Tiered Label Space: Decouples observation status (δ_p, right-censoring) from epistemic 
   label strength (S_p, e.g., WeakSZZ vs. ManualVerified).
2. Inverse Probability Weighting (IPW): Adjusts the evaluation distribution by weighting
   observed outcomes by 1 / P(assign | X), approximating a randomized controlled trial.
3. Positivity Assumption Safeguard: Implements weight clipping and Stratified Auditing to 
   ensure that P(assign | X) > 0 holds true across the feature space.

Standards Complied:
- Causal Inference Best Practices: Enforces weight clipping (e.g., 95th percentile) to 
  prevent variance explosion from infinitesimal propensity scores.
- Strict Label Segregation: Explicitly raises exceptions if noisy `WeakSZZ` labels are 
  used in the primary calibration loop, forcing empirical rigor.
"""

import logging
from enum import Enum, unique
from dataclasses import dataclass
from typing import List, Optional

logger = logging.getLogger(__name__)

@unique
class LabelStrength(Enum):
    """
    Epistemic strength of the defect label. 
    Crucial for preventing SZZ noise from contaminating the calibration loop.
    """
    MANUAL_VERIFIED = "ManualVerified"  # Ground truth, manually audited by researchers
    WEAK_SZZ = "WeakSZZ"                # Heuristically linked via SZZ (noisy, for cohort monitoring only)
    NA = "NA"                           # No defect observed (Right-censored)


@dataclass(frozen=True)
class TieredLabelSpace:
    """
    Formal representation of L_p = <T_p, δ_p, S_p>.
    Separates the temporal observation state from the defect label strength.
    """
    pr_id: str
    observation_days: float      # T_p: Time elapsed since merge (tracks right-censoring)
    defect_observed: bool        # δ_p: 1 if defect reported/fixed, 0 otherwise
    strength: LabelStrength      # S_p: Epistemic strength of the label

    def __post_init__(self):
        if not self.defect_observed and self.strength != LabelStrength.NA:
            raise ValueError("If no defect is observed, label strength must strictly be 'NA'.")
        if self.defect_observed and self.strength == LabelStrength.NA:
            raise ValueError("Observed defects must have an assigned epistemic strength.")


@dataclass(frozen=True)
class CalibrationRecord:
    """
    A single observational record for IPW calibration.
    """
    pr_id: str
    assigned_to_human: bool      # A: Treatment assignment (Was it routed to a human?)
    propensity_score: float      # P(A=1 | X): Probability of assignment given observables
    label: TieredLabelSpace      # L_p: Post-merge outcome


class IPWCalibrator:
    """
    Computes Inverse Probability Weights to correct for routing-induced selection bias.
    """
    
    def __init__(self, max_weight_cap: float = 20.0):
        """
        Args:
            max_weight_cap (float): Caps the maximum IPW weight to prevent variance explosion
                                    caused by violation of the positivity assumption (P -> 0).
                                    Common practice in causal inference (e.g., Robins et al.).
        """
        self.max_weight_cap = max_weight_cap

    def compute_weighted_yield(self, records: List[CalibrationRecord]) -> float:
        """
        Computes the bias-adjusted cumulative yield for RQ1 evaluation.
        
        Strict Academic Safeguard: This function will mathematically reject any record 
        attempting to calibrate the core heuristic using 'WeakSZZ' labels.
        
        Args:
            records: List of historical assignment records with their outcomes.
            
        Returns:
            float: The IPW-weighted cumulative yield.
        """
        weighted_yield = 0.0
        processed_count = 0

        for record in records:
            # ---------------------------------------------------------
            # Safeguard 1: Reject Weak Labels for Core Calibration
            # ---------------------------------------------------------
            if record.label.defect_observed and record.label.strength == LabelStrength.WEAK_SZZ:
                raise ValueError(
                    f"Academic Malpractice Prevention: PR {record.pr_id} uses a 'WeakSZZ' label. "
                    f"Calibration must be anchored strictly on 'ManualVerified' data to prevent "
                    f"optimizing for SZZ heuristic noise."
                )

            # We only evaluate the yield (defects found) within the subset 
            # that was ACTUALLY assigned to humans (Treatment = 1).
            if record.assigned_to_human and record.label.defect_observed:
                p_score = record.propensity_score
                
                # ---------------------------------------------------------
                # Safeguard 2: Positivity Assumption & Variance Control
                # ---------------------------------------------------------
                # In causal inference (Robins et al.), positivity requires P(A|X) >= eps > 0.
                # Propensity scores < 1e-4 violate positivity and cause unstable weight explosion.
                eps = 1e-4
                if p_score < eps:
                    logger.warning(
                        f"Positivity violation on PR {record.pr_id}. Propensity {p_score} < {eps}. "
                        f"Counterfactual yield is theoretically unrecoverable. Skipping."
                    )
                    continue
                
                # IPW Formula: W = 1 / P(Assign | X)
                raw_weight = 1.0 / max(p_score, eps)
                
                # Variance control via weight clipping (standard Hajek / Robins clipping)
                clipped_weight = min(raw_weight, self.max_weight_cap)
                
                weighted_yield += clipped_weight
                processed_count += 1
                
        logger.info(
            f"IPW Calibration complete. Processed {processed_count} verified defect records. "
            f"Weighted Cumulative Yield: {weighted_yield:.2f}"
        )
        return weighted_yield


class StratifiedAuditor:
    """
    Implements the Exploration mechanism to guarantee the Positivity Assumption 
    (P(assign | X) > 0) in real-world deployment.
    """
    
    @staticmethod
    def select_audit_candidates(
        deferred_tasks: List[str], 
        audit_budget_fraction: float = 0.05,
        seed: Optional[int] = None
    ) -> List[str]:
        """
        Randomly elevates a fraction of deferred tasks (those the heuristic proxy deemed 
        low-yield) into the human review queue.
        
        This structural intervention ensures that no region of the feature space is 
        permanently blinded, allowing the IPW calibrator to capture counterfactuals 
        that would otherwise be lost.
        
        Args:
            deferred_tasks: List of PR IDs that were deferred by the Phase 4 Scheduler.
            audit_budget_fraction: The percentage of total budget reserved for random auditing.
            seed: Optional integer seed for deterministic audit candidate selection.
            
        Returns:
            List[str]: PR IDs selected for mandatory human audit.
        """
        import random
        rng = random.Random(seed) if seed is not None else random
        
        audit_count = max(1, int(len(deferred_tasks) * audit_budget_fraction))
        
        # Ensure reproducibility in deterministic sampling
        audited_prs = rng.sample(deferred_tasks, min(audit_count, len(deferred_tasks)))
        
        logger.info(f"Stratified Auditor selected {len(audited_prs)} deferred tasks for random auditing.")
        return audited_prs
